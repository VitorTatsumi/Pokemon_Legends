export function laMissionsForRegion(regionId: HisuiRegionId | null, kind?: LaMissionKind | 'all') {
  if (!regionId) return []
  return LA_MISSIONS.filter((m) => {
    if (m.regionId !== regionId) return false
    if (kind && kind !== 'all' && m.kind !== kind) return false
    return true
  })
}

export function laMissionCountByRegion(kind: LaMissionKind | 'all' = 'all') {
  const counts: Partial<Record<HisuiRegionId, number>> = {}
  for (const m of LA_MISSIONS) {
    if (kind !== 'all' && m.kind !== kind) continue
    counts[m.regionId] = (counts[m.regionId] ?? 0) + 1
  }
  return counts
}

export function laMissionMapPosition(
  mission: LaMission,
  subMap: { x: number; y: number },
  siblingsAtSub: LaMission[],
): { x: number; y: number } {
  const idx = siblingsAtSub.findIndex((m) => m.id === mission.id)
  const total = siblingsAtSub.length
  if (total <= 1 || idx < 0) return { x: subMap.x, y: subMap.y }
  const angle = (idx / total) * Math.PI * 2
  const radius = 2.2 + (idx % 4) * 0.45
  return {
    x: Math.min(96, Math.max(4, subMap.x + Math.cos(angle) * radius)),
    y: Math.min(96, Math.max(4, subMap.y + Math.sin(angle) * radius)),
  }
}
