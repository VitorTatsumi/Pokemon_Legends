export function getLzaEntryByDex(dex: number) {
  return LZA_POKEDEX.find((e) => e.dex === dex) ?? null
}

/** Wild Zone IDs where this species appears (regular or alpha). */
export function wildZonesForDex(dex: number): number[] {
  const zones: number[] = []
  for (const zone of WILD_ZONES) {
    const hit =
      zone.pokemon.some((p) => p.dex === dex) || zone.alphas.some((a) => a.dex === dex)
    if (hit) zones.push(zone.id)
  }
  return zones
}

